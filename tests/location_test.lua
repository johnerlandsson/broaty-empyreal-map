  L.room_info(f, { id = 'ship.41', area = 7, areaName = {} })
  eq(L.message(f).area, nil)
  eq(L.message(f).areaName, nil)
end)

test('reset clears the area', function()
  local f = L.new()
  L.room_info(f, { id = 'ship.41', area = 'ship.41', areaName = 'Magpie' })
  L.reset(f)
  eq(L.message(f).area, nil)
  eq(L.message(f).areaName, nil)
end)

test('empyreal_room for a new room clears the previous area', function()
  local f = L.new()
  L.room_info(f, { id = 'tiss.market', area = 'tiss', areaName = 'Tiss Station' })
  L.empyreal_room(f, { id = 'ship.41' })
