  eq(m.area, 'ship.41')
  eq(m.areaName, 'Magpie')
end)

test('entering a lift clears the area', function()
  local f = L.new()
  L.room_info(f, { id = 'tiss.market', area = 'tiss', areaName = 'Tiss Station' })
  L.empyreal_room(f, { id = 'lift.1', part = 'lift', vehicle = { id = 'lift.1' } })
