  eq(m.area, nil)
  eq(m.areaName, nil)
end)

-- Empyreal.Room's `ship`, as the game sends it since 2026-10-22: `class` is the hull id,
-- `kind` its name.
local FAIR_COPY = { class = 'courier', id = 'ship.72', kind = 'courier', name = 'Fair Copy' }
local MAGPIE = { class = 'skiff', id = 'ship.41', kind = 'prospecting skiff', name = 'Magpie' }

test('empyreal_room carries the ship\'s hull and its name', function()
  local f = L.new()
  L.room_info(f, { id = 'ship.41', name = 'Cockpit of the Magpie', area = 'ship.41', areaName = 'Magpie' })
  eq(L.empyreal_room(f, { id = 'ship.41', gravity = 0, ship = MAGPIE }), true)
  local m = L.message(f)
  eq(m.hull, 'skiff')
  eq(m.hullName, 'prospecting skiff')
  eq(m.areaName, 'Magpie')
end)

test('a room without a ship clears the hull', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'ship.72', ship = FAIR_COPY })
  L.room_info(f, { id = 'tiss.berth', name = 'Berths' })
  eq(L.message(f).hull, nil)
  L.empyreal_room(f, { id = 'tiss.berth', address = 'Spine 3, starboard' })
  eq(L.message(f).hull, nil)
  eq(L.message(f).hullName, nil)
end)

test('room_info for the same ship keeps the hull', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'ship.72', ship = FAIR_COPY })
  L.room_info(f, { id = 'ship.72', name = 'Cockpit of the Fair Copy', area = 'ship.72', areaName = 'Fair Copy' })
  eq(L.message(f).hull, 'courier')
end)

test('room_info for another ship clears the last hull', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'ship.72', ship = FAIR_COPY })
  L.room_info(f, { id = 'ship.41', name = 'Cockpit of the Magpie' })
  eq(L.message(f).hull, nil)
  eq(L.message(f).hullName, nil)
end)

test('odd-typed ship fields are ignored', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'ship.72', ship = { class = 7, kind = {} } })
  eq(L.message(f).hull, nil)
  eq(L.message(f).hullName, nil)
  L.empyreal_room(f, { id = 'ship.72', ship = 'courier' })
  eq(L.message(f).hull, nil)
end)

test('entering a lift or a reset clears the hull', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'ship.72', ship = FAIR_COPY })
  L.empyreal_room(f, { id = 'tiss.lift-12', part = 'lift', vehicle = { at = 'tiss.berth' } })
  eq(L.message(f).hull, nil)
  L.empyreal_room(f, { id = 'ship.72', ship = FAIR_COPY })
  L.reset(f)
  eq(L.message(f).hull, nil)
  eq(L.message(f).hullName, nil)
end)

test('a repeated ship frame is not a change', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'ship.72', ship = FAIR_COPY })
  eq(L.empyreal_room(f, { id = 'ship.72', ship = FAIR_COPY }), false)
end)

-- The medium freighter, as the game sends her since 2026-10-22: six rooms, `ship.98.<key>`.
local OLD_RELIABLE = { class = 'freighter', id = 'ship.98', kind = 'medium freighter', name = 'Old Reliable' }

local function walk_in(f, key, name)
  L.room_info(f, { id = 'ship.98.' .. key, name = name, area = 'ship.98', areaName = 'Old Reliable' })
end

test('a ship room\'s key is shipRoom', function()
  local f = L.new()
  walk_in(f, 'passage', 'Passage')
  L.empyreal_room(f, { id = 'ship.98.passage', address = 'Deck 1, frame 3', gravity = 0, part = 'deck', ship = OLD_RELIABLE })
  local m = L.message(f)
  eq(m.shipRoom, 'passage')
  eq(m.hull, 'freighter')
  eq(m.hullName, 'medium freighter')
end)

test('shipRoom is only for ship.<n>.<key>', function()
  eq(L.ship_room('ship.98.hold'), 'hold')
  eq(L.ship_room('ship.41'), nil)
  eq(L.ship_room('tiss.berth'), nil)
  eq(L.ship_room('shipyard.a.b'), nil)
  eq(L.ship_room(nil), nil)
  eq(L.ship_room(98), nil)
  local f = L.new()
  L.room_info(f, { id = 'tiss.berth' })
  eq(L.message(f).shipRoom, nil)
end)

test('walking between a ship\'s rooms keeps her hull between the two frames', function()
  local f = L.new()
  walk_in(f, 'passage', 'Passage')
  L.empyreal_room(f, { id = 'ship.98.passage', ship = OLD_RELIABLE })
  walk_in(f, 'hold', 'Cargo Hold')
  local m = L.message(f)
  eq(m.shipRoom, 'hold')
  eq(m.hull, 'freighter')
  eq(m.hullName, 'medium freighter')
end)

test('stepping out of the airlock clears the hull', function()
  local f = L.new()
  walk_in(f, 'airlock', 'Airlock')
  L.empyreal_room(f, { id = 'ship.98.airlock', ship = OLD_RELIABLE })
  L.room_info(f, { id = 'tiss.bay-2', name = 'Bay 2', area = 'tiss', areaName = 'T.I.S.S.' })
  local m = L.message(f)
  eq(m.hull, nil)
  eq(m.shipRoom, nil)
end)

-- A workshop or bunk, as property.ts's roomFor builds it: no address, one exit out to its office room.
local function unit_info(id, name, office)
  return { id = id, name = name, area = 'tiss', areaName = 'T.I.S.S.',
    exits = { OUT = { id = office, inverse = 'IN' } } }
end

test('in a workshop, the message carries its door', function()
  local f = L.new()
  eq(L.room_info(f, unit_info('unit.7', "Juniper's small workshop", 'tiss.workshops')), true)
  L.empyreal_room(f, { id = 'unit.7', address = nil, gravity = 0.6, part = nil })
  local m = L.message(f)
  eq(m.roomId, 'unit.7')
  eq(m.door, 'tiss.workshops')
  eq(m.name, "Juniper's small workshop")
  eq(m.gravity, 0.6)
end)

test('in a bunk, the message carries its door', function()
  local f = L.new()
  L.room_info(f, unit_info('bunk.3', "Juniper's bunk", 'tiss.bunkhouse'))
  eq(L.message(f).door, 'tiss.bunkhouse')
end)

test('stepping out of a workshop clears the door', function()
  local f = L.new()
  L.room_info(f, unit_info('unit.7', "Juniper's small workshop", 'tiss.workshops'))
  L.room_info(f, { id = 'tiss.workshops', name = 'Workshop Row', exits = { IN = { id = 'unit.7' } } })
  eq(L.message(f).door, nil)
end)

test('a content room\'s out exit is not a door', function()
  local f = L.new()
  L.room_info(f, { id = 'tiss.lounge', name = 'Lounge', exits = { OUT = { id = 'tiss.concourse' } } })
  eq(L.message(f).door, nil)
end)

test('odd-shaped exits give no door, never an error', function()
  for _, exits in ipairs({ 'out', 7, {}, { OUT = 'tiss.workshops' }, { OUT = {} }, { OUT = { id = 7 } },
      { OUT = { id = '' } }, { out = { id = 'tiss.workshops' } } }) do
    local f = L.new()
    L.room_info(f, { id = 'unit.7', exits = exits })
    eq(L.message(f).door, nil)
  end
  eq(L.door('unit.7.x', { OUT = { id = 'tiss.workshops' } }), nil)
  eq(L.door('unit.', { OUT = { id = 'tiss.workshops' } }), nil)
  eq(L.door(nil, nil), nil)
end)

test('Empyreal.Room for another room clears the door; for the same room keeps it', function()
  local f = L.new()
  L.room_info(f, unit_info('unit.7', "Juniper's small workshop", 'tiss.workshops'))
  L.empyreal_room(f, { id = 'unit.7', gravity = 0.6 })
  eq(L.message(f).door, 'tiss.workshops')
  L.empyreal_room(f, { id = 'tiss.workshops', address = 'Inner 4:30, fore', gravity = 0.6, part = 'inner' })
  eq(L.message(f).door, nil)
end)

test('reset clears the door', function()
  local f = L.new()
  L.room_info(f, unit_info('bunk.3', "Juniper's bunk", 'tiss.bunkhouse'))
  L.reset(f)
  eq(L.message(f).door, nil)
end)

test("empyreal_room carries the room's district, and another room clears it", function()
  local f = L.new()
  L.room_info(f, { id = 'zennor.embankment', name = 'The Embankment', area = 'zennor' })
  eq(L.empyreal_room(f, { id = 'zennor.embankment', district = 'riverside', gravity = 1 }), true)
  eq(L.message(f).district, 'riverside')
  L.room_info(f, { id = 'zennor.tram', name = 'The Tram', area = 'zennor' })
  eq(L.message(f).district, nil)
  L.empyreal_room(f, { id = 'zennor.tram', district = nil, gravity = 1 })
  eq(L.message(f).district, nil)
end)

test('a district that is not a string is no district', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'zennor.field', district = 5 })
  eq(L.message(f).district, nil)
end)

test('reset clears the district', function()
  local f = L.new()
  L.empyreal_room(f, { id = 'zennor.field', district = 'downs' })
  L.reset(f)
  eq(L.message(f).district, nil)
end)

