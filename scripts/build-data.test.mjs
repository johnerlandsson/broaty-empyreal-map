import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { parse, stringify } from "yaml";
import { build } from "./build-data.mjs";
import { ROOM_FIELDS } from "./source/filter.mjs";

const fixtures = new URL("../tests/fixtures/empyreal", import.meta.url).pathname;
const palette = new URL("../tests/fixtures/tweaks/palette.json", import.meta.url).pathname;
const script = new URL("./build-data.mjs", import.meta.url).pathname;

const temp = () => mkdtempSync(join(tmpdir(), "build-data-"));

/** A copy of the fixture source, outside any git checkout. */
function source() {
  const dir = temp();
  cpSync(fixtures, dir, { recursive: true });
  return dir;
}

/** A tweaks dir with the fixture palette and the given place files. */
function tweaks(places = {}) {
  const dir = temp();
  cpSync(palette, join(dir, "palette.json"));
  for (const [id, tweak] of Object.entries(places)) writeFileSync(join(dir, `${id}.json`), JSON.stringify(tweak));
  return dir;
}

/** Edits an area YAML in a source copy. */
function editArea(src, file, fn) {
  const path = join(src, "content/areas", file);
  const doc = parse(readFileSync(path, "utf8"));
  fn(doc);
  writeFileSync(path, stringify(doc));
}

// Puts the wheel's freight hub room, which the rules can't place.
const placed = { wheelie: { place: { "hub-freight": { x: 1, y: 0, z: 3 } } } };

function setup(places = placed) {
  const dir = temp();
  return { source: source(), tweaksDir: tweaks(places), outDir: join(dir, "out"), reportPath: join(dir, "report.json") };
}

const load = async (file) => (await import(`data:text/javascript,${encodeURIComponent(readFileSync(file, "utf8"))}`)).default;

const lists = (r) => [r.newPlaces, r.noBuilder, ...Object.values(r.rooms), ...Object.values(r.exits), r.unplaced, r.orphans, r.droppedFlags, r.unknownFields];

describe("build", () => {
  it("lists both fixture areas as new places on the first build, and writes them and the index", async () => {
    const opts = setup();
    const { report } = await build(opts);
    expect(report.newPlaces).toEqual([
      { place: "mini", builder: "decks" },
      { place: "wheelie", builder: "wheel" },
    ]);
    expect(report.rooms).toEqual({ added: [], removed: [], renamed: [] });
    expect(await load(join(opts.outDir, "places.js"))).toEqual([
      { id: "mini", prefix: "mini", builder: "decks", docks: ["mini"] },
      { id: "wheelie", prefix: "wheelie", builder: "wheel", docks: ["wheelie"] },
    ]);
    expect(JSON.parse(readFileSync(opts.reportPath, "utf8"))).toEqual(report);
  });

  it("writes each place in the spec's shape, stamped and with the palette inlined", async () => {
    const opts = setup();
    await build(opts);
    const text = readFileSync(join(opts.outDir, "wheelie.js"), "utf8");
    expect(text.split("\n")[0]).toBe("// GENERATED by npm run build:data from empyreal unknown. Do not edit.");
    const w = await load(join(opts.outDir, "wheelie.js"));
    expect(Object.keys(w)).toEqual(["source", "id", "kind", "layout", "levels", "districts", "rooms", "look"]);
    expect(w.source).toEqual({ commit: null, file: "content/areas/wheelie.yaml", tweaks: "data/tweaks/wheelie.json" });
    expect(w.kind).toBe("area");
    expect(w.levels).toEqual([0, 3]);
    expect(w.districts).toEqual([{ id: "concourse", name: "the Concourse", entrance: "wheelie.rim-12" }]);
    expect(w.rooms.map((r) => r.id)).toEqual(w.rooms.map((r) => r.id).sort());
    expect(w.rooms.find((r) => r.id === "wheelie.hub-freight").at).toEqual({ x: 1, y: 0, z: 3 });
    expect(w.look.palette).toEqual(JSON.parse(readFileSync(palette, "utf8")));
    expect(w.look.paint["rim-12"]).toBe("industrial");

    const m = await load(join(opts.outDir, "mini.js"));
    expect(Object.keys(m)).toEqual(["source", "id", "kind", "layout", "levels", "rooms", "look"]);
    expect(m.source).toEqual({ commit: null, file: "content/areas/mini.yaml" });
    expect(m.levels).toEqual([1, 2]);
    expect(m.rooms.find((r) => r.id === "mini.bridge")).toEqual({
      id: "mini.bridge",
      name: "Bridge",
      address: "Deck 2, frame 2",
      at: { deck: 2, frame: 2, side: 0 },
      exits: { down: { to: "mini.hall", via: "hatch", seconds: 4 } },
      gravity: 0,
      canopy: true,
    });
  });

  it("gives no generated room a key outside the kept fields, at and terrain", async () => {
    const opts = setup();
    await build(opts);
    const allowed = [...ROOM_FIELDS, "at", "terrain"];
    for (const id of ["mini", "wheelie"]) {
      for (const r of (await load(join(opts.outDir, `${id}.js`))).rooms) {
        for (const key of Object.keys(r)) expect(allowed).toContain(key);
        for (const flag of r.flags ?? []) expect(["berth", "airlock", "outdoors", "listed"]).toContain(flag);
      }
    }
  });

  it("reports a new place's dropped flags, but not the fields dropped on purpose", async () => {
    const { report } = await build(setup());
    expect(report.droppedFlags).toEqual([
      { place: "mini", flag: "shop", rooms: ["mini.store"] },
      { place: "wheelie", flag: "charger", rooms: ["wheelie.rim-12"] },
    ]);
    expect(report.unknownFields).toEqual([]);
  });

  it("lists a wheel room the rules can't place, with no place tweak, as unplaced", async () => {
    const opts = setup({});
    const { report } = await build(opts);
    expect(report.unplaced).toEqual([{ place: "wheelie", id: "wheelie.hub-freight" }]);
    expect((await load(join(opts.outDir, "wheelie.js"))).rooms.map((r) => r.id)).not.toContain("wheelie.hub-freight");
  });

  it("writes byte-identical files and an empty report on a second build", async () => {
    const opts = setup();
    await build(opts);
    const files = ["mini.js", "wheelie.js", "places.js"].map((f) => join(opts.outDir, f));
    const first = files.map((f) => [readFileSync(f, "utf8"), statSync(f).mtimeMs]);
    const { report } = await build(opts);
    expect(files.map((f) => [readFileSync(f, "utf8"), statSync(f).mtimeMs])).toEqual(first);
    for (const list of lists(report)) expect(list).toEqual([]);
    const again = readFileSync(opts.reportPath, "utf8");
    await build(opts);
    expect(readFileSync(opts.reportPath, "utf8")).toBe(again);
  });

  it("reports a room whose id changed at the same address as renamed", async () => {
    const opts = setup();
    await build(opts);
    const path = join(opts.source, "content/areas/mini.yaml");
    writeFileSync(path, readFileSync(path, "utf8").replaceAll("mini.store", "mini.shop"));
    const { report } = await build(opts);
    expect(report.rooms).toEqual({ added: [], removed: [], renamed: [{ place: "mini", from: "mini.store", to: "mini.shop" }] });
    expect(report.exits).toEqual({ added: [], removed: [] });
  });

  it("reports a removed room, its exits and a tweak still naming it, and still builds the place", async () => {
    const opts = setup({ ...placed, mini: { paint: { bridge: "docks" } } });
    await build(opts);
    editArea(opts.source, "mini.yaml", (doc) => {
      doc.rooms = doc.rooms.filter((r) => r.id !== "mini.bridge");
      delete doc.rooms.find((r) => r.id === "mini.hall").exits.up;
    });
    const { report } = await build(opts);
    expect(report.rooms.removed).toEqual([{ place: "mini", id: "mini.bridge" }]);
    expect(report.exits.removed).toEqual([{ place: "mini", room: "mini.hall", dir: "up", to: "mini.bridge" }]);
    expect(report.orphans).toEqual([{ place: "mini", key: "paint.bridge" }]);
    expect((await load(join(opts.outDir, "mini.js"))).rooms).toHaveLength(3);
  });

  it("lists a none area with no drum or town tweak under noBuilder and writes no file for it", async () => {
    const opts = setup();
    writeFileSync(
      join(opts.source, "content/areas/nowhere.yaml"),
      stringify({ area: { id: "nowhere", name: "Nowhere", gravity: 1 }, rooms: [{ id: "nowhere.hall", name: "Hall", exits: {} }] }),
    );
    const { report } = await build(opts);
    expect(report.noBuilder).toEqual([{ place: "nowhere", file: "content/areas/nowhere.yaml" }]);
    expect(report.newPlaces.map((p) => p.place)).toEqual(["mini", "wheelie"]);
    expect(existsSync(join(opts.outDir, "nowhere.js"))).toBe(false);
    expect((await load(join(opts.outDir, "places.js"))).map((p) => p.id)).toEqual(["mini", "wheelie"]);
  });

  it("builds a none area with a drum tweak as a drum", async () => {
    const opts = setup({ ...placed, nowhere: { drum: { way: "spiral" } } });
    writeFileSync(
      join(opts.source, "content/areas/nowhere.yaml"),
      stringify({ area: { id: "nowhere", name: "Nowhere", gravity: 1 }, rooms: [{ id: "nowhere.hall", name: "Hall", exits: {} }] }),
    );
    const { report } = await build(opts);
    expect(report.noBuilder).toEqual([]);
    expect(report.newPlaces).toContainEqual({ place: "nowhere", builder: "drum" });
    const n = await load(join(opts.outDir, "nowhere.js"));
    expect(n.layout).toEqual({ kind: "none" });
    expect(n.levels).toEqual([0]);
    expect(n.rooms).toEqual([{ id: "nowhere.hall", name: "Hall", exits: {}, gravity: 1 }]);
    expect(n.look.drum).toEqual({ way: "spiral" });
  });

  it("diffs against a hand-made file already in the out dir", async () => {
    const opts = setup();
    await build({ ...opts, outDir: join(opts.outDir, "..", "seed") });
    cpSync(join(opts.outDir, "..", "seed"), opts.outDir, { recursive: true });
    writeFileSync(
      join(opts.outDir, "mini.js"),
      `export default { rooms: [
        { id: "mini.dock", address: "Deck 1, frame 1", exits: { north: "mini.hall" } },
        { id: "mini.hall", address: "Deck 1, frame 2", exits: { south: "mini.dock", east: "mini.store" } },
        { id: "mini.store", address: "Deck 1, frame 3", exits: { west: "mini.hall" } },
      ] };\n`,
    );
    const { report } = await build(opts);
    expect(report.newPlaces).toEqual([]);
    expect(report.rooms.added).toEqual([{ place: "mini", id: "mini.bridge" }]);
    // the hall's way up is new; the new bridge's own exits come with it
    expect(report.exits.added).toEqual([{ place: "mini", room: "mini.hall", dir: "up", to: "mini.bridge" }]);
  });
});

describe("the CLI", () => {
  const run = (args) => spawnSync(process.execPath, [script, ...args], { encoding: "utf8" });

  it("prints the report as short text", () => {
    const o = setup();
    const r = run(["--source", o.source, "--tweaks", o.tweaksDir, "--out", o.outDir, "--report", o.reportPath]);
    expect(r.status).toBe(0);
    expect(r.stdout).toMatch(/new places.*mini \(decks\), wheelie \(wheel\)/);
    const again = run(["--source", o.source, "--tweaks", o.tweaksDir, "--out", o.outDir, "--report", o.reportPath]);
    expect(again.stdout.trim()).toBe("nothing needs you");
  });

  it("stops naming a missing source dir, and writes nothing", () => {
    const o = setup();
    const missing = join(o.source, "nope");
    const r = run(["--source", missing, "--tweaks", o.tweaksDir, "--out", o.outDir, "--report", o.reportPath]);
    expect(r.status).not.toBe(0);
    expect(r.stderr).toContain(missing);
    expect(r.stderr.trim().split("\n")).toHaveLength(1);
    expect(existsSync(o.outDir)).toBe(false);
    expect(existsSync(o.reportPath)).toBe(false);
  });

  it("stops naming the missing file of a partial checkout, and writes nothing", () => {
    const o = setup();
    rmSync(join(o.source, "content/game/world.yaml"));
    const r = run(["--source", o.source, "--tweaks", o.tweaksDir, "--out", o.outDir, "--report", o.reportPath]);
    expect(r.status).not.toBe(0);
    expect(r.stderr).toContain(join(o.source, "content/game/world.yaml"));
    expect(existsSync(o.outDir)).toBe(false);
    expect(existsSync(o.reportPath)).toBe(false);
  });
});
