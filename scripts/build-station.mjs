#!/usr/bin/env node
// Build ui/data/station.js from Mallard session logs plus data/overrides.json.
// Usage: node scripts/build-station.mjs [--logs DIR] [--out ui/data/station.js]

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { collectRooms, completeStation, parseGmcpLines } from "./station-data.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function parseArgs(argv) {
  const args = {
    logs: join(homedir(), ".local/share/net.mallard.app/logs/empyreal-7"),
    out: join(root, "ui/data/station.js"),
  };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--logs") args.logs = resolve(argv[++i]);
    else if (argv[i] === "--out") args.out = resolve(argv[++i]);
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  return args;
}

const { logs, out } = parseArgs(process.argv.slice(2));

// collectRooms treats array order as recency (later frames win), so read the
// logs in filename (date) order and keep each file's lines in order.
const files = readdirSync(logs)
  .filter((f) => f.endsWith(".mallardlog"))
  .sort();
const lines = [];
for (const f of files) {
  for (const line of readFileSync(join(logs, f), "utf8").split("\n")) {
    if (line.length > 0) lines.push(line);
  }
}

const overrides = JSON.parse(readFileSync(join(root, "data/overrides.json"), "utf8"));
const rooms = completeStation(collectRooms(parseGmcpLines(lines)), overrides);

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// Generated by scripts/build-station.mjs — do not edit.\nexport default " +
    JSON.stringify({ wrap: 24, rooms }, null, 1) +
    ";\n",
);

const walked = rooms.filter((r) => r.walked).length;
const closed = rooms.filter((r) => r.closed).length;
console.log(`${rooms.length} rooms (${walked} walked, ${closed} closed)`);
