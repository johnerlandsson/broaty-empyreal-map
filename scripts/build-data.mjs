#!/usr/bin/env node
// Build the map's place data from the Empyreal source and the tweak files: ui/data/<area>.js for
// each area with a builder, ui/data/places.js, ui/data/plans/<plan>.js for each ship plan (and a
// one-room plan for each hull without one), ui/data/ships.js, and the sync report. Reads the
// source, never writes it.
// Usage: node scripts/build-data.mjs [--source DIR] [--tweaks DIR] [--out DIR] [--report PATH]

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keepArea, keepRoom, ROOM_FIELDS } from "./source/filter.mjs";
import { hullClashes, overlaps } from "./source/footprints.mjs";
import { placeRooms } from "./source/place.mjs";
import { loadSource } from "./source/read.mjs";
import { diffRooms, droppedOf, emptyReport, formatReport, sortReport } from "./source/report.mjs";
import { loadTweaks, originOf, resolveLook, resolveTweak, via } from "./source/tweaks.mjs";
import { RINGS } from "./source/wheel.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** A generated room's keys, in order: the kept fields, with `at` and `terrain` after the address. */
const ROOM_KEYS = ["id", "name", "address", "at", "terrain", ...ROOM_FIELDS.slice(3)];
/** The look's keys, in order (resolveLook's, then the palette). */
const LOOK_KEYS = ["paint", "fixtures", "footprints", "hull", "view", "drum", "town", "wheel", "palette"];
/** What a checkout must have; loadSource reads each. */
const SOURCE_PATHS = ["content/areas", "content/plans", "content/game/hulls.yaml", "content/game/world.yaml"];

function ordered(obj, keys) {
  const out = {};
  for (const k of keys) if (obj[k] !== undefined) out[k] = obj[k];
  return out;
}

/** decks or wheel by the layout, else drum or town by the tweak section present, else none. */
function builderOf(layoutKind, tweak) {
  if (layoutKind === "decks" || layoutKind === "wheel") return layoutKind;
  if (tweak.drum) return "drum";
  if (tweak.town) return "town";
  return null;
}

/** Decks bottom up; a wheel's rings rim first, as at.z counts them (the hub and spine are 3). */
function levelsOf(layout, rooms) {
  if (layout.kind === "decks") return [...new Set(rooms.filter((r) => r.at).map((r) => r.at.deck))].sort((a, b) => a - b);
  if (layout.kind === "wheel") {
    const levels = RINGS.flatMap((ring, z) => (layout.rings?.[ring] ? [z] : []));
    return layout.hub || layout.spine ? [...levels, 3] : levels;
  }
  return [0];
}

const STAMP = "// GENERATED by npm run build:data from empyreal ";

/** A generated file's text: the stamp, then the value as JSON. */
function moduleText(commit, value) {
  return `${STAMP}${commit ?? "unknown"}. Do not edit.\nexport default ${JSON.stringify(value, null, 2)};\n`;
}

const git = (dir, ...args) => execFileSync("git", ["-C", dir, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });

/** The nearest directory of a path that exists: the path itself, else its closest parent. */
function existing(path) {
  let dir = path;
  while (!existsSync(dir)) dir = dirname(dir);
  return dir;
}

/** Whether a directory is in a git work tree with a commit at HEAD. */
function atHead(dir) {
  try {
    git(dir, "rev-parse", "--verify", "-q", "HEAD");
    return true;
  } catch {
    return false;
  }
}

/**
 * A file as it was before this sync, or null: in a git work tree, as the last commit has it (not
 * there, it's new); elsewhere, as it is on disk. So a build run again mid-sync, after the first
 * wrote its files, still compares with the commit and gives the same report (R14).
 */
function committed(file) {
  const dir = existing(dirname(file));
  if (!atHead(dir)) return existsSync(file) ? readFileSync(file, "utf8") : null;
  try {
    return git(dir, "show", `HEAD:./${relative(dir, file)}`);
  } catch {
    return null;
  }
}

/** The names of the files in a directory before this sync, as committed() reads them. */
function committedNames(outDir) {
  const dir = existing(outDir);
  if (!atHead(dir)) return existsSync(outDir) ? readdirSync(outDir) : [];
  const rel = relative(dir, outDir);
  return git(dir, "ls-tree", "--name-only", "HEAD", `./${rel ? `${rel}/` : ""}`).split("\n").filter(Boolean).map((f) => basename(f));
}

/** The previous build's report, or null. */
function previousReport(path) {
  const text = committed(path);
  if (text === null) return null;
  try {
    return JSON.parse(text);
  } catch (err) {
    throw new Error(`${path}: ${err.message}`);
  }
}

/**
 * The index module: a static import of every place file, the index array as default, and `data`,
 * id -> place data, so a new place needs no code change. Names are JS-safe; two ids that clash throw.
 */
function indexText(commit, places) {
  const names = new Map();
  for (const { id } of places) {
    const name = `place_${id.replace(/\W/g, "_")}`;
    if ([...names.values()].includes(name)) throw new Error(`area ${id}: its name as an import clashes with another area's`);
    names.set(id, name);
  }
  const imports = places.map(({ id }) => `import ${names.get(id)} from ${JSON.stringify(`./${id}.js`)};`);
  const data = places.map(({ id }) => `  ${JSON.stringify(id)}: ${names.get(id)},`);
  return `${STAMP}${commit ?? "unknown"}. Do not edit.\n${imports.join("\n")}\n\nexport default ${JSON.stringify(places, null, 2)};\n\nexport const data = {\n${data.join("\n")}\n};\n`;
}

/**
 * The hull index module: a static import of every plan file, `{hulls}` as default (each ship hull's
 * id, name, class and plan) and `plans`, plan id -> plan data. Names are JS-safe; two that clash throw.
 */
function shipsText(commit, hulls, planIds) {
  const names = new Map();
  for (const id of planIds) {
    const name = `plan_${id.replace(/\W/g, "_")}`;
    if ([...names.values()].includes(name)) throw new Error(`plan ${id}: its name as an import clashes with another plan's`);
    names.set(id, name);
  }
  const imports = planIds.map((id) => `import ${names.get(id)} from ${JSON.stringify(`./plans/${id}.js`)};`);
  const data = planIds.map((id) => `  ${JSON.stringify(id)}: ${names.get(id)},`);
  return `${STAMP}${commit ?? "unknown"}. Do not edit.\n${imports.join("\n")}\n\nexport default ${JSON.stringify({ hulls }, null, 2)};\n\nexport const plans = {\n${data.join("\n")}\n};\n`;
}

/** The out dir's index files, which are generated but no place's. */
const INDEXES = ["places.js", "ships.js"];

/** The ids of the generated place files (stamped; hand-made files aren't) among the names, each read by `read`. */
function generatedIds(outDir, names, read) {
  return names
    .filter((f) => f.endsWith(".js") && !INDEXES.includes(f))
    .filter((f) => read(join(outDir, f))?.startsWith(STAMP))
    .map((f) => f.slice(0, -".js".length));
}

/** The rooms of a file as it was before this sync (generated or hand-made), or null. */
async function before(file) {
  const text = committed(file);
  if (text === null) return null;
  // A data: URL, so a file rewritten in this process isn't served from the module cache.
  const mod = await import(`data:text/javascript,${encodeURIComponent(text)}`);
  return mod.default?.rooms ?? [];
}

/** Writes a file only if its content changed, through a temp file renamed into place. */
function writeIfChanged(file, text) {
  if (existsSync(file) && readFileSync(file, "utf8") === text) return;
  mkdirSync(dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.tmp`;
  writeFileSync(temp, text);
  renameSync(temp, file);
}

/**
 * Each pair of rooms on a deck whose outlines overlap where one is reshaped, as a line naming the
 * tweak file, both rooms and the file a footprint comes from through `like`. Rooms neither of
 * which has a footprint are left to the source.
 */
function footprintClashes(id, rooms, footprints, tweaks) {
  const local = (roomId) => roomId.slice(roomId.indexOf(".") + 1);
  const cells = rooms.filter((r) => r.at).map((r) => ({ id: r.id, cell: { x: r.at.side, y: r.at.frame, z: r.at.deck }, fp: footprints[local(r.id)] }));
  const reshaped = new Set(cells.filter((c) => c.fp).map((c) => c.id));
  if (!reshaped.size) return [];
  const named = (roomId) => `${roomId}${reshaped.has(roomId) ? via(id, originOf(id, tweaks, "footprints", local(roomId))) : ""}`;
  return overlaps(cells)
    .filter(([a, b]) => reshaped.has(a) || reshaped.has(b))
    .map(([a, b]) => `data/tweaks/${id}.json: footprints: ${named(a)} and ${named(b)} overlap`);
}

/**
 * Each room a deck's hull path cuts through and each cradle or mast it leaves outside
 * (footprints.mjs's hullClashes), as a line naming the tweak file, the deck's hull and the file it
 * or the footprint or fixtures come from through `like`; a hull from `like` suggests the opt-out.
 */
function hullLines(id, rooms, look, tweaks) {
  const file = `data/tweaks/${id}.json`;
  // the base a value comes from through `like`, or null where it's the place's own
  const base = (key, sub) => {
    const origin = originOf(id, tweaks, key, sub);
    return origin === id ? null : origin;
  };
  return hullClashes(rooms, look).map((clash) => {
    const hullBase = base("hull", clash.deck);
    const hull = `hull.${clash.deck}${hullBase ? ` (from ${hullBase}.json via like)` : ""}`;
    const optOut = hullBase ? `; add "hull": {"${clash.deck}": null} to ${id}.json to keep the box` : "";
    if (clash.room) {
      const room = clash.room.slice(clash.room.indexOf(".") + 1);
      const fpBase = look.footprints[room] ? base("footprints", room) : null;
      return `${file}: ${hull} cuts through ${clash.room}${fpBase ? ` (footprints.${room} from ${fpBase}.json via like)` : ""}${optOut}`;
    }
    const fixturesBase = base("fixtures");
    return `${file}: fixtures[${clash.fixture}] (${clash.type}${fixturesBase ? `, from ${fixturesBase}.json via like` : ""}) is outside ${hull}${optOut}`;
  });
}

/**
 * The plan a ship hull without one gets: `hull-<id>`, on decks, one room at Deck 1, frame 1, her
 * cockpit as the game's cockpitPlan (loader.ts) has it, its kept fields only. Its gravity is the
 * plan's, which build() gives.
 */
function oneRoomPlan(hull) {
  const id = `hull-${hull.id}`;
  const cockpit = { id: `${id}.cockpit`, name: "Cockpit of the {name}", address: "Deck 1, frame 1", exits: {}, flags: ["airlock"], canopy: true };
  return { file: "content/game/hulls.yaml", area: { id, name: hull.name, layout: { kind: "decks" } }, raw: [cockpit], hulls: [hull.id], synthesised: true };
}

/**
 * Throws, naming both, on two places or plans that would share an id (and so a tweak file), or a
 * hull naming a plan the source doesn't have; an area can't be an index file's name.
 */
function checkIds(areas, plans, ships) {
  const where = new Map(); // id -> what has it
  for (const { file, area } of areas) {
    if (INDEXES.includes(`${area.id}.js`)) throw new Error(`content/areas/${file}: an area can't be called ${area.id} (ui/data/${area.id}.js is an index)`);
    where.set(area.id, `content/areas/${file}`);
  }
  for (const plan of plans) {
    const id = plan.area.id;
    const what = plan.synthesised ? `hull ${plan.hulls[0]}'s plan ${id} (content/game/hulls.yaml)` : `plan ${id} (${plan.file})`;
    if (where.has(id)) throw new Error(`${what} has the same id as ${where.get(id)}. Nothing written`);
    where.set(id, plan.synthesised ? what : plan.file);
  }
  const ids = new Set(plans.filter((p) => !p.synthesised).map((p) => p.area.id));
  for (const hull of ships) {
    if (hull.plan !== undefined && !ids.has(hull.plan)) throw new Error(`content/game/hulls.yaml: hull ${hull.id} names plan ${hull.plan}, which content/plans doesn't have. Nothing written`);
  }
}

/**
 * Builds one area or plan's file into `ctx.files`, adding to the report and the clashes; a place
 * no builder draws goes under noBuilder and gets none. A plan's report entries carry kind plan.
 * @returns {Promise<{builder: string} | null>}
 */
async function placeFile({ commit, tweaks, report, files, clashes }, { kind, file, area, raw, path, hulls, synthesised }) {
  const id = area.id;
  const tagged = (entry) => (kind === "plan" ? { ...entry, kind } : entry);
  const kept = keepArea(area).area;
  const layout = kept.layout ?? { kind: "none" };
  const tweak = resolveTweak(id, tweaks);
  const builder = builderOf(layout.kind, tweak);
  if (!builder) {
    report.noBuilder.push(tagged({ place: id, file }));
    return null;
  }

  const { rooms: all, unplaced } = placeRooms(area, raw, tweak.place ?? {});
  // A drum places only the rooms its tweak's drum.rooms lists; any other is unplaced, as a
  // wheel room the rules can't place is.
  const onDrum = builder === "drum" ? new Set(Object.keys(tweak.drum.rooms ?? {}).map((local) => `${id}.${local}`)) : null;
  const placed = onDrum ? all.filter((r) => onDrum.has(r.id)) : all;
  if (onDrum) unplaced.push(...all.filter((r) => !onDrum.has(r.id)).map((r) => r.id));
  report.unplaced.push(...unplaced.map((u) => ({ place: id, id: u })));
  // In the source's order, not sorted: the builders draw rooms in the order they come, and a
  // tie (which cell a district's label takes) goes to the first, so the order is on screen. A
  // synthesised room has only kept fields already.
  const rooms = placed.map(({ at, terrain, ...rest }) => ordered({ ...(synthesised ? rest : keepRoom(rest).room), at, terrain }, ROOM_KEYS));

  const { look, orphans } = resolveLook(id, placed, layout.kind, tweaks);
  report.orphans.push(...orphans.map((key) => ({ place: id, key })));
  if (look.footprints) clashes.push(...footprintClashes(id, placed, look.footprints, tweaks));
  if (look.hull) clashes.push(...hullLines(id, placed, look, tweaks));

  // A new place is listed whole; an existing one diffs against its file.
  const was = await before(path);
  if (was === null) {
    report.newPlaces.push(tagged({ place: id, builder }));
  } else {
    const diff = diffRooms(id, was, rooms);
    for (const k of Object.keys(diff.rooms)) report.rooms[k].push(...diff.rooms[k]);
    for (const k of Object.keys(diff.exits)) report.exits[k].push(...diff.exits[k]);
  }

  const data = {
    source: ordered({ commit, file, tweaks: tweaks.places[id] ? `data/tweaks/${id}.json` : undefined }, ["commit", "file", "tweaks"]),
    id,
    name: kept.name,
    kind,
    gravity: kept.gravity,
    hulls,
    layout,
    levels: levelsOf(layout, rooms),
    districts: kept.districts,
    rooms,
    look: ordered({ ...look, palette: tweaks.palette }, LOOK_KEYS),
  };
  const keys = ["source", "id", "name", "kind", "gravity", ...(kind === "plan" ? ["hulls"] : []), "layout", "levels", "districts", "rooms", "look"];
  files.set(path, moduleText(commit, ordered(data, keys)));
  return { builder };
}

/**
 * Builds every place, the index and the report. Reads and checks everything before writing
 * anything, so a missing source, a bad tweak or a partial checkout writes nothing. What changed is
 * against the last commit when the out dir is in a git work tree, else against the files there.
 * @param {{source: string, tweaksDir: string, outDir: string, reportPath: string, tweaksShownAs?: string}} opts
 *   `tweaksShownAs` names the tweaks dir in messages, for a copy of data/tweaks read from elsewhere.
 * @returns {Promise<{report: object}>}
 */
export async function build({ source, tweaksDir, outDir, reportPath, tweaksShownAs }) {
  for (const path of SOURCE_PATHS) {
    if (!existsSync(join(source, path))) throw new Error(`Empyreal source not found: no ${join(source, path)}`);
  }
  const areasDir = join(source, "content/areas");
  if (!readdirSync(areasDir).some((f) => f.endsWith(".yaml"))) throw new Error(`Empyreal source has no areas: no *.yaml in ${areasDir}`);
  const src = loadSource(source);
  const tweaks = loadTweaks(tweaksDir, { shownAs: tweaksShownAs });
  const previous = previousReport(reportPath);
  const report = emptyReport(src.commit);
  const files = new Map(); // path -> text
  const places = [];
  const clashes = []; // every hull and footprint clash, so one build lists them all

  // Every plan, the source's and one for each ship hull without one, with the hulls built to it.
  const ships = src.hulls.filter((h) => h.class !== "station");
  const plans = [
    ...src.plans.map(({ file, area, rooms }) => ({ file: `content/plans/${file}`, area, raw: rooms, hulls: [] })),
    ...ships.filter((h) => h.plan === undefined).map(oneRoomPlan),
  ];
  checkIds(src.areas, plans, ships);
  const planOf = new Map(plans.map((p) => [p.area.id, p]));
  for (const hull of ships) if (hull.plan !== undefined) planOf.get(hull.plan).hulls.push(hull.id);

  // Dropped flags and fields are named by name, the first build their name appears anywhere in the
  // source; a nested field by its dotted name ("car.perStop").
  const dropped = [...src.areas, ...src.plans].flatMap(({ area, rooms }) => [
    { place: area.id, dropped: { ...keepArea(area).dropped, flags: [] } },
    ...rooms.map((raw) => ({ place: area.id, dropped: keepRoom(raw).dropped })),
  ]);
  Object.assign(report, droppedOf(dropped, previous));

  const ctx = { commit: src.commit, tweaks, report, files, clashes };
  for (const { file, area, rooms: raw } of src.areas) {
    const id = area.id;
    const built = await placeFile(ctx, { kind: "area", file: `content/areas/${file}`, area, raw, path: join(outDir, `${id}.js`) });
    if (!built) continue;
    const own = new Set(raw.map((r) => r.id));
    const docks = src.world.filter((w) => own.has(w.berth)).map((w) => w.id).sort();
    places.push({ id, prefix: id, builder: built.builder, docks });
  }
  const planIds = [];
  for (const plan of plans) {
    // A plan's name is its own, else its first hull's; its gravity its own, else the world's
    // for ships (loader.ts), and a room's its own, else the plan's.
    const name = plan.area.name ?? ships.find((h) => h.id === plan.hulls[0])?.name;
    const area = { ...plan.area, name, gravity: plan.area.gravity ?? src.shipGravity };
    const built = await placeFile(ctx, { kind: "plan", ...plan, area, path: join(outDir, "plans", `${plan.area.id}.js`) });
    if (built) planIds.push(plan.area.id);
  }

  if (clashes.length === 1) throw new Error(`${clashes[0]}. Nothing written`);
  if (clashes.length) throw new Error(`${clashes.length} hull and footprint clashes. Nothing written\n${clashes.join("\n")}`);

  // A generated file whose area has left the source goes; a hand-made one stays. The report lists
  // those the last commit had; any on disk goes. A source without any of them is a partial checkout.
  const areaIds = new Set(src.areas.map((a) => a.area.id));
  const had = generatedIds(outDir, committedNames(outDir), committed);
  const gone = had.filter((id) => !areaIds.has(id));
  if (had.length && gone.length === had.length) {
    throw new Error(`this build would remove every place the map has (${had.sort().join(", ")}): is ${source} a whole checkout? Nothing written`);
  }
  report.removedPlaces.push(...gone.map((place) => ({ place })));
  const plansDir = join(outDir, "plans");
  const planSet = new Set(plans.map((p) => p.area.id));
  report.removedPlaces.push(...generatedIds(plansDir, committedNames(plansDir), committed).filter((id) => !planSet.has(id)).map((place) => ({ place, kind: "plan" })));
  const disk = (file) => (existsSync(file) ? readFileSync(file, "utf8") : null);
  const stale = (dir, ids) => (existsSync(dir) ? generatedIds(dir, readdirSync(dir), disk).filter((id) => !ids.has(id)).map((id) => join(dir, `${id}.js`)) : []);
  const remove = [...stale(outDir, areaIds), ...stale(plansDir, planSet)];

  places.sort((a, b) => (a.id < b.id ? -1 : 1));
  files.set(join(outDir, "places.js"), indexText(src.commit, places));
  planIds.sort();
  const hulls = Object.fromEntries(
    [...ships].sort((a, b) => (a.id < b.id ? -1 : 1)).map((h) => [h.id, { ...h, plan: h.plan ?? `hull-${h.id}` }]),
  );
  files.set(join(outDir, "ships.js"), shipsText(src.commit, hulls, planIds));
  sortReport(report);
  files.set(reportPath, `${JSON.stringify(report, null, 2)}\n`);

  for (const [path, text] of files) writeIfChanged(path, text);
  for (const file of remove) rmSync(file);
  return { report };
}

function parseArgs(argv) {
  const args = {
    source: join(homedir(), "dev/empyreal"),
    tweaksDir: join(root, "data/tweaks"),
    outDir: join(root, "ui/data"),
    reportPath: join(root, "data/sync-report.json"),
  };
  const flags = { "--source": "source", "--tweaks": "tweaksDir", "--out": "outDir", "--report": "reportPath" };
  for (let i = 0; i < argv.length; i++) {
    const key = flags[argv[i]];
    if (!key) throw new Error(`Unknown argument: ${argv[i]}`);
    if (argv[i + 1] === undefined) throw new Error(`${argv[i]} needs a value`);
    args[key] = resolve(argv[++i]);
  }
  return args;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { report } = await build(parseArgs(process.argv.slice(2)));
    console.log(formatReport(report));
  } catch (err) {
    console.error(`build:data: ${err.message}`);
    process.exit(1);
  }
}
