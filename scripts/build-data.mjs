#!/usr/bin/env node
// Build the map's place data from the Empyreal source and the tweak files: ui/data/<area>.js for
// each area with a builder, ui/data/places.js, and the sync report. Reads the source, never writes it.
// Usage: node scripts/build-data.mjs [--source DIR] [--tweaks DIR] [--out DIR] [--report PATH]

import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keepArea, keepRoom, ROOM_FIELDS } from "./source/filter.mjs";
import { placeRooms } from "./source/place.mjs";
import { loadSource } from "./source/read.mjs";
import { diffRooms, droppedOf, emptyReport, formatReport, sortReport } from "./source/report.mjs";
import { loadTweaks, resolveLook, resolveTweak } from "./source/tweaks.mjs";
import { RINGS } from "./source/wheel.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** A generated room's keys, in order: the kept fields, with `at` and `terrain` after the address. */
const ROOM_KEYS = ["id", "name", "address", "at", "terrain", ...ROOM_FIELDS.slice(3)];
/** The look's keys, in order (resolveLook's, then the palette). */
const LOOK_KEYS = ["paint", "fixtures", "view", "drum", "town", "wheel", "palette"];
/** What a checkout must have; loadSource reads each. */
const SOURCE_PATHS = ["content/areas", "content/plans", "content/game/hulls.yaml", "content/game/world.yaml"];

function ordered(obj, keys) {
  const out = {};
  for (const k of keys) if (obj[k] !== undefined) out[k] = obj[k];
  return out;
}

/** decks or wheel by the layout, else drum or town by the tweak section present, else none. */
function builderOf(layoutKind, tweak) {
  if (layoutKind === "decks" || layoutKind === "wheel") return layoutKind;
  if (tweak.drum) return "drum";
  if (tweak.town) return "town";
  return null;
}

/** Decks bottom up; a wheel's rings rim first, as at.z counts them (the hub and spine are 3). */
function levelsOf(layout, rooms) {
  if (layout.kind === "decks") return [...new Set(rooms.filter((r) => r.at).map((r) => r.at.deck))].sort((a, b) => a - b);
  if (layout.kind === "wheel") {
    const levels = RINGS.flatMap((ring, z) => (layout.rings?.[ring] ? [z] : []));
    return layout.hub || layout.spine ? [...levels, 3] : levels;
  }
  return [0];
}

const STAMP = "// GENERATED by npm run build:data from empyreal ";

/** A generated file's text: the stamp, then the value as JSON. */
function moduleText(commit, value) {
  return `${STAMP}${commit ?? "unknown"}. Do not edit.\nexport default ${JSON.stringify(value, null, 2)};\n`;
}

/** The previous build's report, or null. */
function previousReport(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (err) {
    throw new Error(`${path}: ${err.message}`);
  }
}

/** The ids of generated place files in the out dir (stamped; hand-made files aren't). */
function generatedIds(outDir) {
  if (!existsSync(outDir)) return [];
  return readdirSync(outDir)
    .filter((f) => f.endsWith(".js") && f !== "places.js")
    .filter((f) => readFileSync(join(outDir, f), "utf8").startsWith(STAMP))
    .map((f) => f.slice(0, -".js".length));
}

/** The rooms of a file already in the out dir (generated or hand-made), or null. */
async function before(file) {
  if (!existsSync(file)) return null;
  // A data: URL, so a file rewritten in this process isn't served from the module cache.
  const mod = await import(`data:text/javascript,${encodeURIComponent(readFileSync(file, "utf8"))}`);
  return mod.default?.rooms ?? [];
}

/** Writes a file only if its content changed, through a temp file renamed into place. */
function writeIfChanged(file, text) {
  if (existsSync(file) && readFileSync(file, "utf8") === text) return;
  mkdirSync(dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.tmp`;
  writeFileSync(temp, text);
  renameSync(temp, file);
}

/**
 * Builds every place, the index and the report. Reads and checks everything before writing
 * anything, so a missing source or a bad tweak writes nothing.
 * @param {{source: string, tweaksDir: string, outDir: string, reportPath: string}} opts
 * @returns {Promise<{report: object}>}
 */
export async function build({ source, tweaksDir, outDir, reportPath }) {
  for (const path of SOURCE_PATHS) {
    if (!existsSync(join(source, path))) throw new Error(`Empyreal source not found: no ${join(source, path)}`);
  }
  const src = loadSource(source);
  const tweaks = loadTweaks(tweaksDir);
  const previous = previousReport(reportPath);
  const report = emptyReport(src.commit);
  const files = new Map(); // path -> text
  const places = [];

  // Stage 1 reads and places the plans, to check them, but doesn't write them.
  for (const { area, rooms } of src.plans) placeRooms(area, rooms);

  // Dropped flags and fields are named by name, the first build their name appears anywhere in the source.
  const dropped = [...src.areas, ...src.plans].flatMap(({ area, rooms }) =>
    rooms.map((raw) => ({ place: area.id, dropped: keepRoom(raw).dropped })),
  );
  Object.assign(report, droppedOf(dropped, previous));

  for (const { file, area, rooms: raw } of src.areas) {
    const id = area.id;
    if (id === "places") throw new Error(`content/areas/${file}: an area can't be called places (ui/data/places.js is the index)`);
    const kept = keepArea(area);
    const layout = kept.layout ?? { kind: "none" };
    const tweak = resolveTweak(id, tweaks);
    const builder = builderOf(layout.kind, tweak);
    if (!builder) {
      report.noBuilder.push({ place: id, file: `content/areas/${file}` });
      continue;
    }

    const { rooms: placed, unplaced } = placeRooms(area, raw, tweak.place ?? {});
    report.unplaced.push(...unplaced.map((u) => ({ place: id, id: u })));
    // In the source's order, not sorted: the builders draw rooms in the order they come, and a
    // tie (which cell a district's label takes) goes to the first, so the order is on screen.
    const rooms = placed.map(({ at, terrain, ...rest }) => ordered({ ...keepRoom(rest).room, at, terrain }, ROOM_KEYS));

    const { look, orphans } = resolveLook(id, placed, layout.kind, tweaks);
    report.orphans.push(...orphans.map((key) => ({ place: id, key })));

    // A new place is listed whole; an existing one diffs against its file.
    const path = join(outDir, `${id}.js`);
    const was = await before(path);
    if (was === null) {
      report.newPlaces.push({ place: id, builder });
    } else {
      const diff = diffRooms(id, was, rooms);
      for (const k of Object.keys(diff.rooms)) report.rooms[k].push(...diff.rooms[k]);
      for (const k of Object.keys(diff.exits)) report.exits[k].push(...diff.exits[k]);
    }

    const data = {
      source: ordered(
        { commit: src.commit, file: `content/areas/${file}`, tweaks: tweaks.places[id] ? `data/tweaks/${id}.json` : undefined },
        ["commit", "file", "tweaks"],
      ),
      id,
      kind: "area",
      layout,
      levels: levelsOf(layout, rooms),
      districts: kept.districts,
      rooms,
      look: ordered({ ...look, palette: tweaks.palette }, LOOK_KEYS),
    };
    files.set(path, moduleText(src.commit, ordered(data, ["source", "id", "kind", "layout", "levels", "districts", "rooms", "look"])));

    const own = new Set(raw.map((r) => r.id));
    const docks = src.world.filter((w) => own.has(w.berth)).map((w) => w.id).sort();
    places.push({ id, prefix: id, builder, docks });
  }

  // A generated file whose area has left the source goes; a hand-made one stays.
  const areaIds = new Set(src.areas.map((a) => a.area.id));
  const gone = generatedIds(outDir).filter((id) => !areaIds.has(id));
  report.removedPlaces.push(...gone.map((place) => ({ place })));

  places.sort((a, b) => (a.id < b.id ? -1 : 1));
  files.set(join(outDir, "places.js"), moduleText(src.commit, places));
  sortReport(report);
  files.set(reportPath, `${JSON.stringify(report, null, 2)}\n`);

  for (const [path, text] of files) writeIfChanged(path, text);
  for (const id of gone) rmSync(join(outDir, `${id}.js`));
  return { report };
}

function parseArgs(argv) {
  const args = {
    source: join(homedir(), "dev/empyreal"),
    tweaksDir: join(root, "data/tweaks"),
    outDir: join(root, "ui/data"),
    reportPath: join(root, "data/sync-report.json"),
  };
  const flags = { "--source": "source", "--tweaks": "tweaksDir", "--out": "outDir", "--report": "reportPath" };
  for (let i = 0; i < argv.length; i++) {
    const key = flags[argv[i]];
    if (!key) throw new Error(`Unknown argument: ${argv[i]}`);
    if (argv[i + 1] === undefined) throw new Error(`${argv[i]} needs a value`);
    args[key] = resolve(argv[++i]);
  }
  return args;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { report } = await build(parseArgs(process.argv.slice(2)));
    console.log(formatReport(report));
  } catch (err) {
    console.error(`build:data: ${err.message}`);
    process.exit(1);
  }
}
